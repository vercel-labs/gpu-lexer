import { runtimeTensorLayout } from "../src/model-layout.js";

const WEIGHT_ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_";

export function promotedModelContents(model) {
  const promoted = {
    formatVersion: model.formatVersion,
    model: model.model,
    featureVersion: model.featureVersion,
    inputSize: model.inputSize,
    hiddenSize: model.hiddenSize,
    architecture: model.architecture,
    outputSize: model.outputSize,
    quantization: model.quantization,
    weightEncoding: model.weightEncoding,
    weights: model.weights,
  };
  return "// Generated by `pnpm model:promote`. Do not edit by hand.\n" +
    `export const promotedModel=${JSON.stringify(promoted, null, 2)};\n`;
}

export function runtimeModelContents(model) {
  let sourceOffset = 0;
  for (const tensor of model.quantization.tensors) {
    if (tensor.offset !== sourceOffset || tensor.length < 1 || !(tensor.scale > 0)) {
      throw new Error(`runtime tensor ${tensor.name} is not contiguous`);
    }
    sourceOffset += tensor.length;
  }
  if (sourceOffset !== model.quantization.parameterCount || model.weights.length !== sourceOffset) {
    throw new Error("runtime model weight count is invalid");
  }

  const tensors = runtimeTensorLayout(model);
  const ranges = [];
  let weights = "";
  let offset = 0;
  for (const tensor of tensors) {
    if (tensor.offset !== offset) {
      throw new Error(`runtime tensor ${tensor.name} has an invalid compact offset`);
    }
    offset += tensor.length;
    ranges.push(offset, shortestEquivalentScale(model, tensor));
    for (let range = 0; range < tensor.sourceRanges.length; range += 2) {
      weights += model.weights.slice(tensor.sourceRanges[range], tensor.sourceRanges[range + 1]);
    }
  }
  if (weights.length !== offset) {
    throw new Error("runtime model compact weight count is invalid");
  }

  return "// Generated by `pnpm build:core` or `pnpm model:promote`. Do not edit by hand.\n" +
    `export const HIDDEN_SIZE=${model.hiddenSize};\n` +
    `export const WEIGHT_BITS=${model.quantization.bits};\n` +
    `export const WEIGHT_RANGES=${JSON.stringify(ranges)};\n` +
    `export const WEIGHTS=${JSON.stringify(weights)};\n`;
}

function shortestEquivalentScale(model, tensor) {
  const values = new Set();
  for (let range = 0; range < tensor.sourceRanges.length; range += 2) {
    for (let index = tensor.sourceRanges[range]; index < tensor.sourceRanges[range + 1]; index++) {
      const encoded = WEIGHT_ALPHABET.indexOf(model.weights[index]);
      if (encoded < 0) throw new Error(`runtime tensor ${tensor.name} has an invalid weight symbol`);
      values.add(encoded & 1 ? -(encoded + 1) / 2 : encoded / 2);
    }
  }

  const original = tensor.scale;
  let best = original;
  let bestLength = JSON.stringify(original).length;
  for (let precision = 1; precision <= 17; precision++) {
    const candidate = Number(original.toPrecision(precision));
    const length = JSON.stringify(candidate).length;
    if (candidate > 0 && length < bestLength && sameFloat32Products(values, original, candidate)) {
      best = candidate;
      bestLength = length;
    }
  }
  if (!sameFloat32Products(values, original, best)) {
    throw new Error(`runtime tensor ${tensor.name} scale compaction changed a Float32 weight`);
  }
  return best;
}

function sameFloat32Products(values, original, candidate) {
  for (const value of values) {
    if (!Object.is(Math.fround(value * original), Math.fround(value * candidate))) return false;
  }
  return true;
}
