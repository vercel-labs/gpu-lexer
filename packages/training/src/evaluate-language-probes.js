import { readFile, readdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { loadFloatCheckpoint } from "./checkpoint.js";
import { createLabeler } from "./label.js";
import { dequantizeTensors } from "./quantization.js";
import { createTreeRecord, treeProbabilities } from "./tree-model.js";
import { promotedRunPath } from "./promoted-run.generated.js";

const manifestPath = fileURLToPath(new URL("../data/language-probes.json", import.meta.url));
const outputPath = fileURLToPath(new URL("../../../apps/website/app/language-probes.generated.ts", import.meta.url));

const sourceDirectory = argument("--source-dir");
const probes = JSON.parse(await readFile(manifestPath, "utf8"));
const checkpoint = await loadFloatCheckpoint(promotedRunPath);
const { metadata } = checkpoint;
const shape = {
  hiddenSize: metadata.hiddenSize,
  classifierSize: metadata.architecture.classifierDimensions,
  hashBuckets: metadata.architecture.lexemeHashBuckets,
};
const entries = await readdir(checkpoint.path);
const weightName = entries.find((name) => new RegExp(`^weights-int${metadata.quantization.bits}-.+\\.bin$`).test(name));
if (!weightName) throw new Error(`stored int${metadata.quantization.bits} weights are missing`);
const packed = await readFile(resolve(checkpoint.path, weightName));
const model = dequantizeTensors(packed, metadata.quantization);
const labeler = await createLabeler({ langs: [...new Set(probes.map(({ shiki }) => shiki))] });
const results = [];

try {
  for (const probe of probes) {
    const source = sourceDirectory
      ? await readFile(resolve(sourceDirectory, probe.id), "utf8")
      : await fetchSource(probe.url);
    const sourceLabels = labeler.labelSource(source, probe.shiki);
    const { record } = createTreeRecord({
      source, sourceLabels, sourceLabelsVersion: 1, language: probe.id,
      family: probe.id, sourceName: "external-probe", path: probe.fileName,
      origin: "repository-pinned-probe",
    }, shape.hashBuckets, { retainSource: true, featureVersion: metadata.featureVersion });
    const probabilities = treeProbabilities(model, record, shape);
    let correct = 0, support = 0;
    for (let part = 0; part < record.targets.length; part++) {
      if (!record.supervisionWeights[part]) continue;
      support++;
      if (argmax(probabilities[part]) === record.targets[part]) correct++;
    }
    const accuracy = correct / Math.max(1, support);
    results.push({ ...probe, accuracy, correct, support, characters: source.length, range: band(accuracy) });
    console.log(`${probe.id.padEnd(9)} ${(accuracy * 100).toFixed(2)}% (${correct}/${support} parts)`);
  }
} finally {
  labeler.dispose();
}

const generated = {
  runId: metadata.runId,
  generatedAt: new Date().toISOString(),
  results,
};
await writeFile(outputPath,
  `// Generated by \`pnpm probes:evaluate\`. Do not edit by hand.\n` +
  `export const languageProbes = Object.freeze(${JSON.stringify(generated, null, 2)});\n`);
console.log(`website probes: ${outputPath}`);

function argument(name) {
  const index = process.argv.indexOf(name);
  return index < 0 ? null : process.argv[index + 1];
}
async function fetchSource(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`failed to fetch ${url}: HTTP ${response.status}`);
  return response.text();
}
function argmax(values) {
  let best = 0;
  for (let index = 1; index < values.length; index++) if (values[index] > values[best]) best = index;
  return best;
}
function band(accuracy) {
  if (accuracy >= 0.95) return "95–100%";
  if (accuracy >= 0.9) return "90–<95%";
  if (accuracy >= 0.8) return "80–<90%";
  if (accuracy >= 0.7) return "70–<80%";
  if (accuracy >= 0.6) return "60–<70%";
  if (accuracy >= 0.5) return "50–<60%";
  return "<50%";
}
